/**
 * Sample media for the message-media stories.
 *
 * Everything here is a self-contained data URL so the stories render
 * identically offline, in CI, and in a published static Storybook — no asset
 * pipeline, no network, nothing to 404. The images are inline SVG (the same
 * trick `slicc-image-preview.stories.ts` uses); the clip is a 192x108, 2 s,
 * silent H.264 file, kept deliberately tiny because its only job is to prove
 * the `<video>` chrome — control bar, poster frame, aspect ratio — lays out
 * correctly inside the chat column.
 */

/** A labelled placeholder frame, as an SVG data URL. */
export function sampleImage(label: string, from: string, to: string, w = 640, h = 400): string {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${w} ${h}" width="${w}" height="${h}">
  <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
    <stop offset="0%" stop-color="${from}"/><stop offset="100%" stop-color="${to}"/>
  </linearGradient></defs>
  <rect width="${w}" height="${h}" fill="url(#g)"/>
  <text x="${w / 2}" y="${h / 2 + 12}" font-family="ui-sans-serif,system-ui,sans-serif"
        font-size="34" font-weight="600" text-anchor="middle" fill="#fff" fill-opacity="0.92">${label}</text>
</svg>`;
  return `data:image/svg+xml;utf8,${encodeURIComponent(svg)}`;
}

